  const name = (chapterName || "").trim();
  if (SECTION_TPL[name]) return SECTION_TPL[name](ctx);
  if (CHAPTER_TPL[name]) return CHAPTER_TPL[name](ctx);
  // 前缀匹配（如树节点带编号差异）
  for (const k of Object.keys(SECTION_TPL)) if (name.includes(k) || k.includes(name)) return SECTION_TPL[k](ctx);
  for (const k of Object.keys(CHAPTER_TPL)) if (name.includes(k) || k.includes(name)) return CHAPTER_TPL[k](ctx);
  return SECTION_TPL["16.1 二次根式"](ctx);
